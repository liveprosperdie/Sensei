"""
llm_json.py — tolerant parsing of the JSON envelope the routing LLM returns.

WHY THIS EXISTS (live bug, 2026-07): get_akira_response threw
JSONDecodeError('Unterminated string starting at ...') three times in a row on
one request — a long multi-paragraph office_control|word|insert parameter. Two
independent causes, both real:

  1. TRUNCATION. The routing call has a max_tokens budget. A multi-paragraph
     document body inside a parameter string blows past it, so the reply ends
     mid-string and there is no closing quote or brace at all. json.loads can
     never accept that, and no prompt wording prevents it once the content is
     long enough — which is why long content must be generated by a SEPARATE
     call (gemini_content) and never travel inside the routing JSON.
  2. RAW CONTROL CHARACTERS AND UNESCAPED QUOTES. Models emit real newlines and
     bare " inside string values instead of \\n and \\". This is recoverable
     and is exactly what the repair pass below fixes.

  3. TWO COMPLETE OBJECTS IN ONE REPLY, with the model second-guessing itself
     in prose between them. NOT a repair case — the prompt forbids it — but the
     parser still takes the first complete object so a self-correcting reply
     can never be stitched into an action nobody asked for.

So parsing is deliberately two-stage: strict json.loads first (the normal
path, zero risk), then ONE repair pass that re-escapes what the model got
wrong and closes what the model never finished. The repair reports whether it
had to close an unterminated string, because a truncated string means the
CONTENT IS CUT OFF — the caller must refuse to act on it rather than typing
half a document into the user's file.

No Windows/TTS/network imports: this module is exercised headlessly.
"""

from __future__ import annotations

import json
import re

# Escape characters JSON itself allows after a backslash. Anything else is the
# model escaping something it shouldn't (e.g. \d), and the backslash has to be
# doubled or json.loads rejects the whole document.
_VALID_ESCAPES = '"\\/bfnrtu'

# A closing quote is followed (ignoring whitespace) by one of these. Anything
# else means the quote is literal text the model forgot to escape.
_AFTER_STRING = ',:}]'


def _strip_wrapper(raw: str) -> str:
    """Drop code fences and any prose around the JSON object."""
    text = (raw or "").replace("```json", "").replace("```", "").strip()
    start = text.find("{")
    if start > 0:
        text = text[start:]
    return text.strip()


def _repair(text: str) -> tuple[str, bool]:
    """Re-escape and close a malformed JSON object.

    Returns (repaired_text, truncated) where truncated is True when a string
    literal was still open at end of input — i.e. the model's reply was cut
    off mid-value and the last value is incomplete.
    """
    out: list[str] = []
    stack: list[str] = []
    in_str = False
    escaped = False
    truncated = False
    i, n = 0, len(text)

    while i < n:
        c = text[i]

        if in_str:
            if escaped:
                out.append(c)
                escaped = False
                i += 1
                continue
            if c == "\\":
                nxt = text[i + 1] if i + 1 < n else ""
                if nxt in _VALID_ESCAPES and nxt != "":
                    out.append(c)
                    escaped = True
                else:
                    out.append("\\\\")       # stray backslash -> literal
                i += 1
                continue
            if c == '"':
                j = i + 1
                while j < n and text[j] in " \t\r\n":
                    j += 1
                if j >= n or text[j] in _AFTER_STRING:
                    in_str = False
                    out.append(c)
                else:
                    out.append('\\"')        # unescaped inner quote
                i += 1
                continue
            if c == "\n":
                out.append("\\n")
            elif c == "\r":
                out.append("\\r")
            elif c == "\t":
                out.append("\\t")
            elif ord(c) < 0x20:
                out.append("\\u%04x" % ord(c))
            else:
                out.append(c)
            i += 1
            continue

        if c == '"':
            in_str = True
        elif c in "{[":
            stack.append("}" if c == "{" else "]")
        elif c in "}]":
            if stack:
                stack.pop()
        out.append(c)
        i += 1

    if in_str:
        truncated = True
        if escaped:
            out.pop()                        # dangling backslash before EOF
        out.append('"')

    # An object or array still open at end of input means the reply never
    # finished either — same "do not act on this" signal as an open string.
    if stack:
        truncated = True

    repaired = "".join(out) + "".join(reversed(stack))
    # Trailing commas are illegal in JSON but common in truncated output.
    repaired = re.sub(r",\s*([}\]])", r"\1", repaired)
    return repaired, truncated


def _candidates(repaired: str) -> list[str]:
    """Progressively more aggressive salvage forms of a repaired document.

    A reply cut off right after a KEY ("...,\"parameter\") closes into
    {"a":1,"parameter"} — valid-looking but missing a value. Two salvage moves
    cover it: give the dangling key an empty value, or drop the dangling pair
    entirely.
    """
    forms = [repaired]
    m = re.search(r'("(?:[^"\\]|\\.)*")\s*([}\]]*)$', repaired)
    if m:
        forms.append(repaired[:m.start(1)] + m.group(1) + ': ""' + m.group(2))
        dropped = re.sub(r',\s*"(?:[^"\\]|\\.)*"\s*([}\]]*)$', r"\1", repaired)
        if dropped != repaired:
            forms.append(dropped)
    # A dangling "key": with no value at all.
    forms.append(re.sub(r':\s*([}\]]*)$', r': ""\1', repaired))
    return forms


def parse(raw: str) -> tuple[dict | None, dict]:
    """Parse an LLM JSON reply.

    Returns (obj, info). obj is None when nothing salvageable was found.
    info = {"repaired": bool, "truncated": bool} — truncated means a string
    value was cut off, so any content inside this object is INCOMPLETE and
    must not be written anywhere.
    """
    info = {"repaired": False, "truncated": False}
    text = _strip_wrapper(raw)
    if not text:
        return None, info

    try:
        obj = json.loads(text)
        return (obj if isinstance(obj, dict) else None), info
    except json.JSONDecodeError as first:
        print(f"[llm_json] strict parse failed: {first}")

    # TWO COMPLETE OBJECTS IN ONE REPLY (live bug, 2026-07): the model emitted a
    # full object, then prose second-guessing itself, then another full object.
    # That is a GENERATION problem — AKIRA_PROMPT now forbids it outright — but
    # the repair pass below must never see it: re-escaping and closing a
    # two-object document can merge them into a plausible-looking envelope that
    # runs an action nobody chose. So take the FIRST complete object and drop
    # the rest, before any repair. raw_decode stops at the end of object one.
    try:
        obj, end = json.JSONDecoder().raw_decode(text)
        if isinstance(obj, dict):
            print(f"[llm_json] took the first complete object, discarded "
                  f"{len(text) - end} trailing chars (self-correcting reply)")
            return obj, info
    except json.JSONDecodeError:
        pass

    # Pre-clean known delimiter-quote corruption patterns (e.g. ]"} or }"})
    cleaned_text = re.sub(r'([}\]])\s*"\s*([}\]])', r'\1\2', text)
    cleaned_text = re.sub(r'([}\]])\s*"\s*$', r'\1', cleaned_text)
    if cleaned_text != text:
        try:
            obj = json.loads(cleaned_text)
            if isinstance(obj, dict):
                info["repaired"] = True
                print(f"[llm_json] repaired delimiter-quote corruption: keys={list(obj)}")
                return obj, info
        except json.JSONDecodeError:
            text = cleaned_text

    repaired, truncated = _repair(text)
    info["truncated"] = truncated
    for candidate in _candidates(repaired):
        try:
            obj = json.loads(candidate)
        except json.JSONDecodeError:
            # Try delimiter repair on candidate as well
            cand_clean = re.sub(r'([}\]])\s*"\s*([}\]])', r'\1\2', candidate)
            cand_clean = re.sub(r'([}\]])\s*"\s*$', r'\1', cand_clean)
            try:
                obj = json.loads(cand_clean)
            except json.JSONDecodeError:
                continue
        if isinstance(obj, dict):
            info["repaired"] = True
            print(f"[llm_json] repaired (truncated={truncated}) "
                  f"keys={list(obj)}")
            return obj, info

    try:
        print(f"[llm_json] unrepairable: {text[:300]!r}")
    except Exception:
        safe_repr = text[:300].encode("ascii", errors="backslashreplace").decode("ascii")
        print(f"[llm_json] unrepairable: {safe_repr}")
    return None, info


def extract_spoken_text(raw: str) -> str:
    """Extract natural spoken text from any string that may accidentally contain a JSON envelope,
    raw dict formatting, or code fences.

    If raw is a JSON object or contains keys like 'spoken_response', 'response', 'summary', 'message',
    this extracts only that spoken message. If it's already plain text, returns it cleanly.
    Ensures raw JSON syntax, quotes, and 'thought' fields are never read aloud by TTS.
    """
    if not raw or not isinstance(raw, str):
        return ""
    text = raw.strip()
    if not text:
        return ""

    # Check if text looks like JSON or contains JSON-like braces
    if ("{" in text and "}" in text) or text.startswith("{"):
        try:
            obj, _ = parse(text)
            if isinstance(obj, dict):
                # Search for known spoken keys in priority order
                for key in ("spoken_response", "response", "summary", "message", "content", "reply", "text"):
                    val = obj.get(key)
                    if isinstance(val, str) and val.strip():
                        res = val.strip()
                        if ("{" in res and "}" in res) and res != text:
                            return extract_spoken_text(res)
                        return res
                # If it's a dict without standard spoken keys, use first non-thought string value
                for k, v in obj.items():
                    if k not in ("thought", "actions", "mode", "tone", "confirmation_required", "end_session") and isinstance(v, str) and v.strip():
                        return v.strip()
        except Exception:
            pass

        # Regex fallback for {"response": "..."} or {"spoken_response": "..."} even if JSON is malformed
        m = re.search(r'"(?:spoken_response|response|summary|message|reply)"\s*:\s*"((?:[^"\\]|\\.)*)"', text, re.IGNORECASE)
        if m:
            val = m.group(1).encode("utf-8").decode("unicode_escape", errors="replace")
            if val.strip():
                return val.strip()

    # If it starts and ends with stray quotes, strip them
    if (text.startswith('"') and text.endswith('"')) or (text.startswith("'") and text.endswith("'")):
        if len(text) >= 2:
            text = text[1:-1].strip()

    return text